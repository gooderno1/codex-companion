import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtemp, mkdir, writeFile, readFile, readdir, rm, appendFile, rename } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
const require = createRequire(import.meta.url);
const { readCodexProjects, projectForSession } = require("../dist-electron/main/codexProjects.js");
const { ActivityIndex } = require("../dist-electron/main/state/activityIndex.js");
const { ActivityDetailsService } = require("../dist-electron/main/activityDetailsService.js");
const { CodexSessionCacheStore } = require("../dist-electron/main/state/codexSessionCacheStore.js");
const { buildProjectOverviewPeriod, DashboardService } = require("../dist-electron/main/collectors/dashboardCollector.js");
const fixture = await mkdtemp(path.join(os.tmpdir(), "companion-project-index-"));
const home = path.join(fixture, "codex"), store = path.join(fixture, "companion");
const startAt = "2026-01-01T00:00:00Z", endAt = "2026-01-03T00:00:00Z";
let index;
try {
  await mkdir(path.join(home, "sessions"), { recursive: true });
  await mkdir(path.join(home, "archived_sessions"));
  const root = path.join(fixture, "work"), nested = path.join(root, "docs");
  await mkdir(nested, { recursive: true });
  const state = { "local-projects": { a: { id: "a", name: "旧名称", rootPaths: [root] }, b: { id: "b", name: "无 Git 项目", rootPaths: [nested] } }, "thread-project-assignments": { explicit: { projectKind: "local", projectId: "a" } }, "projectless-thread-ids": ["none"], "thread-workspace-root-hints": { hint: nested }, "app-server-project-id-by-legacy-project-id-by-host": { [`local:${home}`]: { a: "new-a", b: "new-b" } } };
  await writeFile(path.join(home, ".codex-global-state.json"), JSON.stringify(state));
  let catalog = await readCodexProjects(home);
  const assign = (id, cwd = nested) => projectForSession(catalog, { sessionId: id, cwd });
  assert.equal(assign("nested"), "b");
  assert.equal(assign("explicit", path.join(fixture, "worktree")), "a");
  assert.equal(assign("none"), "__unattributed__");
  assert.equal(assign("hint", null), "b");
  assert.equal(assign("prefix", root + "-different"), "__unattributed__");
  catalog.assignments.set("deleted-project", "deleted");
  assert.equal(assign("deleted-project"), "__unattributed__", "不能把显式归属已删除项目的会话重新猜测分配");
  const legacyHome = path.join(fixture, "legacy");
  await mkdir(legacyHome);
  await writeFile(path.join(legacyHome, ".codex-global-state.json"), JSON.stringify({ "electron-saved-workspace-roots": [root], "electron-workspace-root-labels": { [root]: "旧版保存的 Codex 项目" } }));
  const legacy = await readCodexProjects(legacyHome);
  assert.equal(legacy.projects[0].name, "旧版保存的 Codex 项目");
  assert.equal(projectForSession(legacy, { sessionId: "old", cwd: root }), legacy.projects[0].id);
  const dbPath = path.join(home, "state_5.sqlite"), source = new DatabaseSync(dbPath);
  source.exec("CREATE TABLE projects(id TEXT, name TEXT, position INT); CREATE TABLE project_roots(project_id TEXT, path TEXT, position INT); CREATE TABLE threads(id TEXT,project_id TEXT);");
  source.prepare("INSERT INTO projects VALUES(?,?,?)").run("new-a", "Codex 当前名称", 0);
  source.prepare("INSERT INTO projects VALUES(?,?,?)").run("new-b", "无 Git 项目", 1);
  source.prepare("INSERT INTO project_roots VALUES(?,?,?)").run("new-a", root, 0);
  source.prepare("INSERT INTO project_roots VALUES(?,?,?)").run("new-b", nested, 0);
  source.prepare("INSERT INTO threads(id,project_id) VALUES(?,?)").run("db-explicit", "new-b");
  source.prepare("INSERT INTO threads(id,project_id) VALUES(?,?)").run("explicit", null);
  source.close();
  const before = await readFile(dbPath);
  catalog = await readCodexProjects(home);
  assert.equal(catalog.projects.length, 2, "新旧项目 ID 合并，不能生成重复项目");
  assert.equal(catalog.projects[0].name, "Codex 当前名称");
  assert.equal(assign("db-explicit", root), "b");
  assert.equal(assign("explicit", null), "a", "尚未完成归属迁移时保留桌面明确归属");
  assert.deepEqual(await readFile(dbPath), before, "不改写 Codex 数据库");
  const duplicate = { ...catalog, projects: [...catalog.projects, { id: "duplicate", name: "同目录另一个项目", rootPaths: [nested] }] };
  assert.equal(projectForSession(duplicate, { sessionId: "ambiguous", cwd: nested }), "__unattributed__", "相同根目录多个项目时不能猜测");
  const file = path.join(home, "sessions", "rollout-2026-01-01-fixture.jsonl");
  const records = [ { type: "session_meta", payload: { id: "nested", timestamp: startAt, cwd: nested } }, { type: "turn_context", payload: { model: "gpt-6-astra" } } ];
  const usage = (timestamp, count) => ({ type: "event_msg", timestamp, payload: { type: "token_count", info: { total_token_usage: { input_tokens: count, cached_input_tokens: 0, output_tokens: 0, total_tokens: count } } } });
  records.push(usage(startAt, 100));
  await writeFile(file, records.map(JSON.stringify).join("\n") + "\n");
  index = new ActivityIndex(store, home);
  assert.deepEqual(await index.refresh(), { parsedFiles: 1, reusedFiles: 0 });
  assert.equal((await index.query({ startAt, endAt })).events[0].tokens.total, 100);
  index.close();
  index = new ActivityIndex(store, home);
  assert.deepEqual(await index.refresh(), { parsedFiles: 0, reusedFiles: 1 }, "重启后复用持久化索引");
  await appendFile(file, JSON.stringify(usage("2026-01-02T00:00:00Z", 180)) + "\n");
  assert.equal((await index.refresh()).parsedFiles, 1);
  let result = await index.query({ startAt, endAt });
  assert.equal(result.events.reduce((n, event) => n + event.tokens.total, 0), 180, "文件增量替换，不重复累加旧事件");
  assert.equal((await index.query({ startAt, endAt: "2026-01-02T00:00:00Z" })).events.length, 1, "SQL 范围右边界排除");
  const overview = buildProjectOverviewPeriod({ repoItems: [], catalog, events: result.events, sessionProjectMap: new Map(), startAt: new Date(startAt), endAt: new Date(endAt), activityField: "today" });
  assert.equal(overview.find(p => p.id === "b").tokenTotal, 180);
  assert.equal(overview.find(p => p.id === "b").codeAvailable, false);
  assert.equal(overview.length, 2, "没有 Git 也保留全部 Codex 项目");
  const sharedRepo = buildProjectOverviewPeriod({ repoItems: [{ path: root, activity: { today: { changedLines: 5, commits: 1 } }, recentCommits: [] }], catalog, events: result.events, sessionProjectMap: new Map(), startAt: new Date(startAt), endAt: new Date(endAt), activityField: "today" });
  assert.equal(sharedRepo.length, 2, "两个 Codex 项目关联同一仓库仍是两个项目");
  assert.equal(sharedRepo.find(p => p.id === "a").tokenTotal, 0);
  assert.equal(sharedRepo.find(p => p.id === "b").tokenTotal, 180);
  assert.ok(sharedRepo.every(p => p.codeAvailable));
  const dbFile = (await readdir(store)).find(name => name.endsWith(".sqlite"));
  const local = new DatabaseSync(path.join(store, dbFile), { readOnly: true });
  assert.match(JSON.stringify(local.prepare("EXPLAIN QUERY PLAN SELECT payload FROM events WHERE at>=? AND at<? ORDER BY at").all(0, Date.now())), /events_at/);
  local.close();
  index.close();
  const stale = new DatabaseSync(path.join(store, dbFile));
  stale.exec("PRAGMA user_version=102");
  for (const row of stale.prepare("SELECT file,seq,payload FROM events").all()) {
    const event = JSON.parse(row.payload); event.apiCostUsd = 0; event.creditsEstimate = 0;
    stale.prepare("UPDATE events SET payload=? WHERE file=? AND seq=?").run(JSON.stringify(event), row.file, row.seq);
  }
  stale.close(); index = new ActivityIndex(store, home);
  assert.equal((await index.refresh()).parsedFiles, 1, "价格升级使旧 SQLite 派生成本失效");
  const revalued = await index.query({ startAt, endAt });
  assert.equal(revalued.events.reduce((sum,e)=>sum+e.apiCostUsd,0), .0018);
  assert.equal(revalued.events.reduce((sum,e)=>sum+e.creditsEstimate,0), .045);
  assert.equal(revalued.events.reduce((sum,e)=>sum+e.tokens.total,0), 180);
  assert.equal((await index.refresh()).reusedFiles, 1, "重估后恢复复用");
  const archived = path.join(home, "archived_sessions", path.basename(file));
  await rename(file, archived);
  await index.refresh();
  assert.equal((await index.query({ startAt, endAt })).events.length, 2, "归档移动不能重复计数");
  await writeFile(archived, records.map(JSON.stringify).join("\n") + "\n");
  await index.refresh();
  assert.equal((await index.query({ startAt, endAt })).events.length, 1, "截断重写移除旧事件");
  const nameSource = new DatabaseSync(dbPath);
  nameSource.exec("ALTER TABLE threads ADD COLUMN name TEXT");
  nameSource.prepare("INSERT INTO threads(id,project_id,name) VALUES(?,?,?)").run("nested", "new-b", "自动会话名称");
  nameSource.close();
  const service = new ActivityDetailsService({ read: async () => ({ codexHome: home }) }, new CodexSessionCacheStore(store));
  const legacySnapshot = { generatedAt: new Date().toISOString(), quotaDisplayVersion: 2, overview: { limitWindows: [] } };
  assert.equal(await new DashboardService({}, { read: async () => legacySnapshot }).getCachedSnapshot(), null, "升级后不能把旧仓库分组缓存重新当成 Codex 项目");
  const details = await service.query({ startAt, endAt });
  assert.equal(details.projects.find(p => p.id === "b").tokens.total, 100);
  assert.equal(details.sessions[0].name, "自动会话名称");
  assert.equal(details.projects.find(p => p.id === "b").code, null, "列表不查询 Git");
  assert.deepEqual(await service.queryCode({ startAt, endAt, projectId: "b" }), { repositories: [] });
  await assert.rejects(service.queryCode({ startAt, endAt, projectId: "arbitrary-path" }));
  const changedSource = new DatabaseSync(dbPath);
  changedSource.prepare("UPDATE threads SET project_id=?, name=? WHERE id=?").run("new-a", "修改后的会话名称", "nested");
  changedSource.prepare("UPDATE projects SET name=? WHERE id=?").run("重命名后的项目", "new-a");
  changedSource.close();
  const reassigned = await service.query({ startAt, endAt });
  assert.equal(reassigned.performance.parsedFiles, 0);
  assert.equal(reassigned.sessions[0].name, "修改后的会话名称", "改名不重建统计索引");
  assert.equal(reassigned.projects.find(p => p.id === "a").tokens.total, 100, "无需重解析 JSONL 即可反映 Codex 修改归属");
  assert.equal(reassigned.projects.find(p => p.id === "a").name, "重命名后的项目");
  service.close();
  await rm(archived);
  await index.refresh();
  result = await index.query({ startAt, endAt });
  assert.equal(result.events.length, 0);
  assert.equal(result.sessions.length, 0, "已删除文件同步清理");
  assert.equal(result.coverage.files, 0);
  console.log("Codex 项目与 SQLite 索引验证通过：新旧 ID、非 Git、嵌套根、显式工作树、无项目、歧义、名称同步、只读边界、重启复用、追加/归档/截断/删除、SQL 索引和按需 Git。");
} finally { index?.close(); await rm(fixture, { recursive: true, force: true }); }
