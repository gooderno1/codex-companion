import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtemp, writeFile, readFile, rm, appendFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
const require = createRequire(import.meta.url);
const { readCodexSessionNames } = require("../dist-electron/main/codexSessionNames.js");
const { formatCompactToken, exactTokenLabel } = require("../dist-electron/shared/tokenFormat.js");
const home = await mkdtemp(path.join(os.tmpdir(), "companion-session-names-"));
try {
  assert.equal((await readCodexSessionNames(home)).size, 0, "无名称元数据时保持无名，不读取正文");
  const index = path.join(home, "session_index.jsonl");
  const entry = (id, thread_name, updated_at) => JSON.stringify({ id, thread_name, updated_at });
  await writeFile(index, [entry("both", "索引旧名称", "2026-09-01"), entry("index-only", "最新名称", "2026-09-17"), entry("index-only", "乱序旧名称", "2026-09-01"), entry("empty-db", "索引补充名称", "2026-09-01"), "null", "{unfinished", entry("blank", "   ", "2026-09-17")].join("\n") + "\n");
  const dbPath = path.join(home, "state_5.sqlite");
  let db = new DatabaseSync(dbPath);
  db.exec("CREATE TABLE threads(id TEXT PRIMARY KEY, name TEXT, title TEXT)");
  db.prepare("INSERT INTO threads VALUES(?,?,?)").run("both", "数据库当前名称", "不能展示的任务初始内容");
  db.prepare("INSERT INTO threads VALUES(?,?,?)").run("empty-db", null, "不能展示的任务初始内容");
  db.prepare("INSERT INTO threads VALUES(?,?,?)").run("unnamed", null, "不能展示的任务初始内容");
  db.close();
  const before = await readFile(dbPath);
  let names = await readCodexSessionNames(home);
  assert.equal(names.get("both"), "数据库当前名称");
  assert.equal(names.get("index-only"), "最新名称");
  assert.equal(names.get("empty-db"), "索引补充名称");
  assert.equal(names.has("blank"), false);
  assert.equal(names.has("unnamed"), false, "不能把 threads.title 的任务正文当作名称");
  assert.deepEqual(await readFile(dbPath), before, "名称读取不改写 Codex 数据库");
  db = new DatabaseSync(dbPath);
  db.prepare("UPDATE threads SET name=? WHERE id=?").run("用户重新命名", "both");
  db.close();
  names = await readCodexSessionNames(home);
  assert.equal(names.get("both"), "用户重新命名");
  await appendFile(index, entry("index-only", "索引更新名称", "2026-09-18") + "\n");
  assert.equal((await readCodexSessionNames(home)).get("index-only"), "索引更新名称");
  db = new DatabaseSync(dbPath);
  db.exec("ALTER TABLE threads DROP COLUMN name");
  db.close();
  assert.equal((await readCodexSessionNames(home)).get("both"), "索引旧名称", "旧 schema 回退名称索引");
  await writeFile(dbPath, "invalid SQLite");
  assert.equal((await readCodexSessionNames(home)).get("index-only"), "索引更新名称", "数据库不可读不阻断已有名称");
} finally { await rm(home, { recursive: true, force: true }); }
for (const [value, expected] of [[null,"未观测"],[0,"0"],[9999,"9,999"],[10000,"1.0 万"],[12500,"1.3 万"],[100000,"10 万"],[100000000,"1.0 亿"],[123456789,"1.2 亿"],[1000000000,"10 亿"]]) assert.equal(formatCompactToken(value), expected);
assert.equal(exactTokenLabel(123456789), "123,456,789 Token");
console.log("会话名称与 Token 显示通过：name / thread_name 优先级、正文排除、缺失 / 旧 schema / 损坏回退、改名、只读边界及万 / 亿单位边界。");
